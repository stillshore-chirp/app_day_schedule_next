export function createTranslator(catalog: MessageCatalog) {
  return (
    key: MessageKey,
    values: readonly (string | number | boolean | null | undefined)[] = [],
  ): string =>
    catalog[key].replace(/\{(\d+)\}/g, (_placeholder, index: string) =>
      String(values[Number(index)] ?? ""),
    );
}

